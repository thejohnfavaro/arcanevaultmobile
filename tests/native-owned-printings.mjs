import assert from 'node:assert/strict';
import fs from 'node:fs';
const screen=fs.readFileSync('app/src/main/java/com/arcanevault/mobile/NativeCatalogScreen.java','utf8');
const backend=fs.readFileSync('app/src/main/java/com/arcanevault/mobile/CatalogStore.java','utf8');
const start=backend.indexOf('JSONObject ownedPhysicalPrintings(Map<String,String> p)');
const finish=backend.indexOf('JSONObject variants(Map<String,String> p)',start);
assert.ok(start>=0 && finish>start,'The SQLite owned printings query exists');
const query=backend.slice(start,finish);
assert.match(screen,/onlyOwnedPhysicalPrintings/);
assert.match(screen,/Show owned physical printings/);
assert.match(screen,/onlyOwnedPhysicalPrintings=!onlyOwnedPhysicalPrintings/);
assert.match(screen,/if\(onlyOwnedPhysicalPrintings\)\{source="physical";owned="owned";\}/);
assert.match(screen,/if\(!"physical"\.equals\(source\)\)onlyOwnedPhysicalPrintings=false/);
assert.match(screen,/onlyOwnedPhysicalPrintings=false;\s*updateCollectionFilters\(\);schedule\(\)/);
assert.match(screen,/printingMode\?catalog\.ownedPhysicalPrintings\(options\):catalog\.search\(options\)/);
assert.match(screen,/if\(printingMode\)\{renderOwnedPrintingRow\(row\);continue;\}/);
assert.match(screen,/showPrintingDetail\(name,printing,imageUrl\)/);
assert.match(screen,/No confirmed printings found\. Name-only physical cards stay in Physical/);
assert.match(query,/FROM physical_printings p/,'Read indexed physical identities');
assert.match(query,/JOIN variants v ON p\.print_id!='' AND v\.print_id=p\.print_id COLLATE NOCASE/,'Only exact printed IDs count when IDs provided');
assert.match(query,/p\.setcode!='' AND p\.collector!=''/,'Fallback needs both set and collector');
assert.match(query,/NOT EXISTS \(SELECT 1 FROM variants other/,'Never guess ambiguous set and collector matches');
assert.match(query,/other\.print_id!=v\.print_id/);
assert.match(query,/SUM\(qty\) qty FROM matches GROUP BY id/,'Multiple rows of one printing aggregate');
assert.match(query,/LIMIT \? OFFSET \?/,'Printing list uses bounded pagination');
assert.match(query,/confirmedPhysicalCopies/,'Show confirmed counts per edition');
assert.doesNotMatch(query,/INSERT\s|UPDATE\s|DELETE\s+FROM /,'Read-only projection cannot rewrite ownership');
console.log('PASS: exact owned physical printings filter uses bounded, unambiguous, read-only edition identities');
